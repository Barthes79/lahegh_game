_RECENT_HISTORY_SIZE = 10

# حافظه‌ی «۱۰ متن اخیر هر کاربر»، فقط در حافظه‌ی پردازش (بین اجراهای مختلف ربات پاک می‌شود).
_recent_by_user: dict[int, list[str]] = {}


def pick_closing_line(telegram_id: int) -> str:
    """
    یک جمله‌ی پایانی تصادفی برمی‌گرداند که (تا حد امکان) در ۱۰ متن اخیر همین کاربر تکراری نباشد.
    """
    recent = _recent_by_user.get(telegram_id, [])
    candidates = [line for line in CLOSING_LINES if line not in recent]
    if not candidates:
        # اگر (به‌ندرت) همه‌ی مجموعه در حافظه‌ی اخیر بود، محدودیت موقتاً نادیده گرفته می‌شود.
        candidates = CLOSING_LINES

    chosen = random.choice(candidates)

    updated_recent = recent + [chosen]
    _recent_by_user[telegram_id] = updated_recent[-_RECENT_HISTORY_SIZE:]

    return chosen


def _reset_for_tests(telegram_id: int | None = None) -> None:
    """فقط برای تست‌ها: پاک کردن حافظه‌ی اخیر (یک کاربر یا همه)."""
    if telegram_id is None:
        _recent_by_user.clear()
    else:
        _recent_by_user.pop(telegram_id, None)
